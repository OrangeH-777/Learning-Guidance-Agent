import { test, expect } from '@playwright/test'

test('register → model → profile → generate → history; narrow screen and safe rendering', async ({ page }, testInfo) => {
  const username = `ui_${testInfo.project.name}_${Date.now().toString().slice(-7)}`
  await page.goto('/login')
  await page.screenshot({ path: `../tests/results/${testInfo.project.name}-login.png` })
  await page.getByRole('button', { name: '还没有账号？创建账号' }).click()
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill('Study2026')
  await page.getByLabel('确认密码').fill('Study2026')
  await page.getByRole('button', { name: '注册并进入' }).click()
  await expect(page.getByRole('heading', { name: '今天，想学懂什么？' })).toBeVisible()
  await page.getByRole('link', { name: '模型设置', exact: true }).click()
  await page.getByLabel('Base URL').fill('https://fixture.invalid/v1')
  await page.getByLabel('模型 ID').fill('fixture-model')
  await page.getByLabel('API Key').fill('browser-test-secret')
  await page.getByRole('button', { name: '保存设置' }).click()
  await expect(page.getByText('设置已保存，请完成连接测试后再生成。')).toBeVisible()
  await page.getByRole('button', { name: '连接测试（可能计费）' }).click()
  await expect(page.getByText('连接测试成功。')).toBeVisible()
  await page.getByRole('link', { name: '学习画像', exact: true }).click()
  await page.getByLabel('知识基础', { exact: true }).fill('已学习数组')
  await page.getByLabel('学习目标', { exact: true }).fill('理解栈和括号匹配')
  await page.getByLabel('学习偏好', { exact: true }).fill('具体示例')
  await page.getByRole('button', { name: '确认并保存画像' }).click()
  await expect(page.getByText('画像已确认，版本 1。')).toBeVisible()
  await page.getByText('通过对话整理画像（使用已配置的模型）').click()
  await page.getByLabel('描述你的学习情况').fill('初学者，希望掌握栈，喜欢具体示例')
  await page.getByRole('button', { name: '发送并整理' }).click()
  await expect(page.getByLabel('知识基础', { exact: true })).toHaveValue('初学者')
  await page.reload()
  await expect(page.getByLabel('知识基础', { exact: true })).toHaveValue('已学习数组')
  await page.getByRole('button', { name: '恢复对话草稿到表单' }).click()
  await expect(page.getByLabel('知识基础', { exact: true })).toHaveValue('初学者')
  await expect(page.getByText('当前版本 1', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '取消修改', exact: true }).click()
  await expect(page.getByLabel('知识基础', { exact: true })).toHaveValue('已学习数组')
  await page.getByLabel('当前课程').selectOption('test_course')
  await expect(page.getByLabel('知识基础', { exact: true })).toHaveValue('')
  await expect(page.getByText('当前版本 0', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '恢复对话草稿到表单' })).toHaveCount(0)
  await page.getByLabel('当前课程').selectOption('data_structure')
  await expect(page.getByLabel('知识基础', { exact: true })).toHaveValue('已学习数组')
  await expect(page.getByRole('button', { name: '恢复对话草稿到表单' })).toBeVisible()
  await page.getByRole('link', { name: '工作台', exact: true }).click()
  await page.getByRole('combobox', { name: '课程', exact: true }).selectOption('test_course')
  await expect(page.getByRole('button', { name: '开始生成' })).toBeDisabled()
  await expect(page.getByText('课程知识索引尚未就绪。资料准备完成后可开始生成。')).toBeVisible()
  await page.getByRole('combobox', { name: '课程', exact: true }).selectOption('data_structure')
  await page.getByLabel('学习主题').fill('栈与括号匹配')
  await page.getByRole('button', { name: '开始生成' }).click()
  await page.getByRole('button', { name: '查看资源' }).click()
  await expect(page.getByRole('heading', { name: '栈的基本概念' })).toBeVisible()
  await expect(page.getByText(/由AI生成，仅供参考 · 自动核验已通过/)).toBeVisible()
  await page.screenshot({ path: `../tests/results/${testInfo.project.name}-resource.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect((await page.getByRole('navigation').boundingBox())?.height).toBeLessThan(50)
  await page.screenshot({ path: `../tests/results/${testInfo.project.name}-mobile.png`, fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.route('**/api/resources/*', async route => {
    const response = await route.fetch()
    const body = await response.json()
    body.content.title = '<img src=x onerror="window.__xss=1">'
    await route.fulfill({ response, json: body })
  })
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('<img src=x onerror="window.__xss=1">')
  expect(await page.locator('h1 img').count()).toBe(0)
  expect(await page.evaluate(() => '__xss' in window)).toBeFalsy()
  await page.unrouteAll()
  await page.getByRole('link', { name: '学习历史', exact: true }).click()
  await expect(page.getByRole('heading', { name: '栈的基本概念' })).toBeVisible()
  await page.getByLabel('主题', { exact: true }).fill('栈')
  await page.getByRole('button', { name: '筛选', exact: true }).click()
  await expect(page).toHaveURL(/topic=/)
  const historyLocation = page.url()
  await page.getByRole('heading', { name: '栈的基本概念' }).click()
  await expect(page).toHaveURL(/resources/)
  await page.getByRole('link', { name: '← 返回学习历史' }).click()
  await expect(page).toHaveURL(historyLocation)
  await expect(page.getByLabel('主题', { exact: true })).toHaveValue('栈')
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => document.activeElement?.tagName)).not.toBe('BODY')
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goto('/history')
  await expect(page).toHaveURL(/\/login$/)
})
