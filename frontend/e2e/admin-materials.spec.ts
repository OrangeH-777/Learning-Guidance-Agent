import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { resolve } from 'node:path'

test('administrator previews and publishes Markdown, PDF and Word as selectable chapters', async ({ page }, testInfo) => {
  if (testInfo.project.name === 'edge') await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/login')
  await page.getByLabel('账号', { exact: true }).fill('browser_admin')
  await page.getByLabel('密码', { exact: true }).fill('BrowserAdmin123')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('link', { name: '公共教材管理', exact: true }).click()
  await expect(page.getByRole('heading', { name: '公共教材管理' })).toBeVisible()
  const courseName = testInfo.project.name + '新课程'
  await page.getByText('新建课程', {exact:true}).click()
  await page.getByLabel('课程名称').fill(courseName)
  await page.getByRole('button', {name:'创建课程',exact:true}).click()
  await expect(page.getByText('课程已创建，请上传第一份教材。')).toBeVisible()
  const courseId = await page.getByLabel('教材所属课程').inputValue()
  const title = `${testInfo.project.name}教材`
  await page.getByLabel('上传教材', { exact: false }).setInputFiles({
    name: '第十章 栈.md', mimeType: 'text/markdown', buffer: Buffer.from('# 栈\n\n栈采用后进先出。<script>window.materialXss=1</script>'),
  })
  await expect(page.getByRole('region', { name: '正文预览' })).toContainText('后进先出')
  await expect(page.getByRole('heading', { name: '2. 教材预览与来源' })).toBeFocused()
  await expect(page.getByRole('heading', { name: '2. 教材预览与来源' })).toBeInViewport()
  await page.getByRole('button', { name: '编辑正文' }).click()
  const content = await page.getByLabel('提取正文（可校正）').inputValue()
  await page.getByLabel('提取正文（可校正）').fill('')
  await expect(page.getByLabel('提取正文（可校正）')).toBeVisible()
  await page.getByLabel('提取正文（可校正）').fill(content)
  await page.getByLabel('章节名称').fill(title)
  await expect(page.getByLabel('章号')).toHaveValue('10')
  await page.getByLabel('章节简介').fill('用入栈与出栈解释后进先出。')
  await page.getByLabel('来源网址').fill('https://example.org/original')
  await page.getByLabel('章节 / 页码').fill('第一章')
  await page.getByLabel('授权或使用依据').fill('浏览器测试原创')
  await expect(page.getByRole('button', { name: '确认并保存公共教材' })).toBeDisabled()
  await page.getByLabel('我已核对正文与来源', { exact: false }).check()
  await page.getByRole('button', { name: '确认并保存公共教材' }).click()
  await expect(page.getByText('公共教材已保存，可在工作台选择本章。')).toBeVisible()
  const root = resolve(import.meta.dirname, '../..')
  const python = resolve(root, process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python')
  for (const [extension, fixture, expected] of [['pdf', 'pdf_bytes', 'LIFO'], ['docx', 'word_bytes', '先进先出']]) {
    const buffer = execFileSync(python, ['-c', `import sys; from tests.unit.test_material_text import ${fixture}; sys.stdout.buffer.write(${fixture}())`], { cwd: root })
    await page.getByLabel('上传教材').setInputFiles({ name: `教材.${extension}`, mimeType: 'application/octet-stream', buffer })
    await expect(page.getByRole('region', { name: '正文预览' })).toContainText(expected)
    await page.getByLabel('章节名称').fill(extension + ' 示例')
    await page.getByLabel('章号').fill(extension === 'pdf' ? '2' : '3')
    await page.getByLabel('来源网址').fill('https://example.org/original')
    await page.getByLabel('章节 / 页码').fill('第一章')
    await page.getByLabel('授权或使用依据').fill('测试原创')
    await page.getByLabel('我已核对正文与来源', { exact: false }).check()
    await page.getByRole('button', { name: '确认并保存公共教材' }).click()
    await expect(page.getByText('公共教材已保存，可在工作台选择本章。')).toBeVisible()
  }
  await page.getByRole('link', { name: '工作台', exact: true }).click()
  await page.getByRole('combobox', { name: '课程', exact: true }).selectOption(courseId)
  const options = page.getByRole('combobox', { name: '教材章节', exact: true }).locator('option')
  await expect(options).toHaveText(['请选择已校对章节', '第 2 章 · pdf 示例', '第 3 章 · docx 示例', '第 10 章 · ' + title])
  await page.getByLabel('教材章节').selectOption({ index: 3 })
  await expect(page.getByText('用入栈与出栈解释后进先出。')).toBeVisible()
  await page.goto('/admin/materials?course=' + courseId)
  const edit = (name: string) => page.locator('.material-list li').filter({ hasText: name }).getByRole('button', {name:'编辑 / 校对'}).click()
  await edit('pdf 示例')
  await page.getByLabel('章号').fill('11')
  await page.getByLabel('章节名称').fill('练习与解析')
  await page.getByLabel('章节简介').fill('练习如何判断出栈顺序。')
  await page.getByLabel('我已核对正文与来源', { exact: false }).check()
  await page.getByRole('button', { name: '确认并保存公共教材' }).click()
  await expect(page.locator('.material-list li').last()).toContainText('练习如何判断出栈顺序。')
  const remove = page.getByRole('button', {name:'删除章节：docx 示例'})
  page.once('dialog', d => d.dismiss())
  await remove.click()
  await expect(remove).toBeVisible()
  page.once('dialog', d => d.accept())
  await remove.click()
  await expect(remove).toHaveCount(0)
  await page.getByRole('link', { name: '工作台', exact: true }).click()
  await page.getByRole('combobox', { name: '课程', exact: true }).selectOption(courseId)
  await expect(options).toHaveText(['请选择已校对章节', '第 10 章 · ' + title, '第 11 章 · 练习与解析'])
  await page.goto('/admin/materials?course=' + courseId)
  await edit(title)
  await expect(page.getByLabel('章节名称')).toHaveValue(title)
  await expect(page.getByRole('heading', { name: '2. 校对已有教材' })).toBeFocused()
  await expect(page.getByRole('heading', { name: '2. 校对已有教材' })).toBeInViewport()
  await page.getByLabel('章节名称').fill(`${title}未保存`)
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', {name:/选择 \/ 上传/}).click()
  await expect(page).toHaveURL(/materials\/review/)
  await expect(page.getByLabel('章节名称')).toHaveValue(`${title}未保存`)
  await page.getByLabel('章节名称').fill(title)
  // A second tab saves while this editor still contains an older revision.
  const auth = await (await page.request.get('/api/auth/session')).json()
  const catalog = await (await page.request.get('/api/admin/courses')).json()
  const current = catalog.find((c: { id: string }) => c.id === courseId)
  const source = current.sources.find((s: { title: string }) => s.title === title)
  const updated = await page.request.post(`/api/admin/courses/${courseId}/materials`, {
    headers: { 'X-CSRF-Token': auth.csrf_token }, data: {
      expected_version: current.version, source_id: source.id, title,
      source_url: source.source_url, section: source.section, license: source.license,
      content: '# 新版\n\n另一个页面保存的教材。', confirmed: true,
    },
  })
  expect(updated.status()).toBe(201)
  await page.getByLabel('我已核对正文与来源', { exact: false }).check()
  await page.getByRole('button', { name: '确认并保存公共教材' }).click()
  await expect(page.getByText('课程教材已更新，请重新加载后保存')).toBeVisible()
  expect(await page.evaluate(() => (window as unknown as Record<string, unknown>).materialXss)).toBeUndefined()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: `../tests/results/${testInfo.project.name}-admin-materials.png`, fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await page.goto('/admin/materials')
  await expect(page).toHaveURL(/\/login$/)
})
